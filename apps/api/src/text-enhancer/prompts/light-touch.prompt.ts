import type { TrackRubric } from '../rubrics/rubric.interface';

export function buildLightTouchPrompt(text: string, rubric: TrackRubric): string {
  return `أنت محرر لغوي. مهمتك تصحيح هذا النص بالحد الأدنى الممكن.

اسمح بهذه التعديلات فقط:
- تصحيح الأخطاء الإملائية.
- تصحيح علامات الترقيم.
- توحيد تنسيق الأرقام والتواريخ بالشكل العربي القياسي.

ممنوع منعاً قاطعاً:
- إعادة صياغة أي جملة صحيحة لغوياً.
- إضافة أو حذف أي كلمة.
- استبدال مفردة بمرادفها.
- تعديل ترتيب الجمل أو الفقرات.
- تعديل المصطلحات الآتية: ${rubric.domainGlossary.join('، ')}.

المسار: ${rubric.trackName}.

أرجع النص المحسّن فقط، بدون أي شرح أو تعليق، وبدون علامات markdown أو أقواس مضافة.

النص الأصلي:
"""
${text}
"""`;
}
