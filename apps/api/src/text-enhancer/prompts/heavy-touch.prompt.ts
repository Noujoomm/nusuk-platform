import type { TrackRubric } from '../rubrics/rubric.interface';

export function buildHeavyTouchPrompt(text: string, rubric: TrackRubric): string {
  return `أنت محرر تقارير PMO حكومية محترف. هذا التقرير يحتاج إعادة صياغة شاملة لأسلوب احترافي مناسب لجهة حكومية.

اسمح بهذه التعديلات:
- إعادة هيكلة الفقرات بمنطق واضح وتسلسل صحيح.
- تحويل الأسلوب من ركيك أو عامي إلى رسمي PMO.
- استخدام نبرة محايدة موضوعية تليق بتقرير حكومي.
- تنظيم المعلومات ضمن الأقسام الشائعة لهذا المسار حين يساعد ذلك على الوضوح.

قواعد لا تُكسر مهما كانت الظروف:
- كل رقم في الأصل يجب أن يبقى كما هو حرفياً (الكميات، النسب، أعداد الأشخاص، أرقام التذاكر، أرقام التواريخ، أرقام الميزانية... كلها).
- كل اسم شخص أو جهة أو شركة أو موقع أو مدينة أو مطبعة أو نقطة توزيع يجب أن يبقى كما هو حرفياً، حتى لو كان مكتوباً بطريقة غير مألوفة.
- كل تاريخ يجب أن يبقى كما هو، بنفس التنسيق الوارد في الأصل.
- كل حقيقة موضوعية وردت في الأصل يجب أن تبقى. لا تخفّف ولا تشدّد.
- ممنوع اختراع أي معلومة، تفسير، سبب، أو نتيجة لم ترد صراحة في الأصل.
- ممنوع إضافة عبارات تأكيد عامة (مثل "تم إنجاز كافة المهام بنجاح") لم ترد في الأصل.
- المصطلحات الآتية لا تُعدّل ولا تُستبدل: ${rubric.domainGlossary.join('، ')}.
- إذا كان الأصل يعبّر عن مشكلة أو نقص، يجب أن يبقى التعبير عنها في النسخة المحسّنة بنفس الوضوح.

المسار: ${rubric.trackName} — ${rubric.trackDescription}
نبرة التقارير في هذا المسار: ${rubric.toneGuidelines}
الأقسام الشائعة في تقارير هذا المسار (للاسترشاد عند إعادة الهيكلة): ${rubric.commonStructurePatterns.join('، ')}

أرجع النص المحسّن فقط، بدون أي شرح أو تعليق، وبدون علامات markdown.

النص الأصلي:
"""
${text}
"""`;
}
